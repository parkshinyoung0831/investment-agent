"""기업 재무 저장소 포트."""
from __future__ import annotations

from collections.abc import Iterable
from datetime import date
from typing import Any, Protocol


class CompanyFinancialRepository(Protocol):
    def gating_universe(self) -> list[dict]: ...
    def tracked_ciks(self) -> set[str]: ...
    def ciks_for_tickers(self, tickers: set[str] | list[str]) -> set[str]: ...
    def tickers_by_cik(self) -> dict[str, list[str]]: ...
    def watchlist_tickers(self) -> set[str]: ...
    def watchlist_expected_reports(self) -> list[dict]: ...
    def last_filed_map(self) -> dict[str, str]: ...
    def processed_filing_accessions(self) -> dict[str, set[str]]: ...
    def ciks_missing_financials(self) -> list[str]: ...
    def mark_empty_filing_targets(self, targets: list, **kwargs: Any) -> int: ...
    def mark_superseded_filing_targets(self, targets: list, **kwargs: Any) -> int: ...
    def mark_processed_filing_targets(self, targets: list, **kwargs: Any) -> int: ...
    def upsert_filings(self, filings: Iterable) -> int: ...
    def reconcile_wide_history(self, cik_ceiling: dict[str, str], floor: date) -> int: ...
    def upsert_core_wide(self, rows: list[dict]) -> int: ...
    def report_anomalies(self, rows: list[dict]) -> int: ...


class SegmentMetricRepository(Protocol):
    """차원 세그먼트 지표 저장소.

    공시 상태는 company와 같은 ``fundamentals.filing_processing``을
    ``content_type='segments'``로 공유한다 — 축이 하나뿐인 표를 둘로 나누면
    같은 accession_no을 두 곳에서 세게 된다.
    """

    def tracked_ciks(self) -> set[str]: ...
    def ciks_for_tickers(self, tickers: set[str] | list[str]) -> set[str]: ...
    def watchlist_tickers(self) -> set[str]: ...
    def existing_accessions(self, forms: Iterable[str] | None = None) -> dict[str, set[str]]: ...
    def accessions_by_source(
        self,
        sources: Iterable[str],
        forms: Iterable[str] | None = None,
    ) -> dict[str, set[str]]: ...
    def ciks_missing_segments(self, period_kind: str | None = None) -> set[str]: ...
    def upsert_filings(self, rows: list[dict]) -> int: ...
    def upsert_segment_metrics(self, rows: list[dict]) -> int: ...
    def upsert_segment_metrics_with_rows(self, rows: list[dict]) -> tuple[int, list[dict]]: ...
    def delete_stale_metrics_for_accessions(
        self,
        pairs: Iterable[tuple[str, str]],
        replacement_rows: list[dict],
    ) -> int: ...
    def hydrate_metric_rows(self, rows: Iterable[dict]) -> list[dict]: ...
    def fetch_metric_years(self, pairs: set[tuple[str, int]]) -> list[dict]: ...
    def delete_history_before(self, cutoff: str) -> dict[str, int]: ...


class ExpectationsRepository(Protocol):
    """시장 예상치·발표 일정·애널리스트 커버리지 저장소."""

    def universe_tracked(self) -> list[str]: ...
    def watchlist_tickers(self) -> list[str]: ...
    def fiscal_periods(self, tickers: list[str]) -> list[dict]: ...
    def tickers_missing_consensus(self, tickers: list[str]) -> set[str]: ...
    def latest_analyst_snapshots(self, tickers: list[str]) -> list[dict]: ...
    def upsert_consensus(self, rows: list[dict]) -> int: ...
    def upsert_schedules(self, rows: list[dict]) -> int: ...
    def upsert_analyst_snapshots(self, rows: list[dict]) -> int: ...
    def prune_earnings_estimates(self, days: int = 1095) -> dict: ...
    def prune_expectation_snapshots(self, recent_days: int = 180) -> dict: ...


class EarningsEventRepository(Protocol):
    def load_fiscal_calendar(self, ticker: str) -> list[dict]: ...
    def load_earnings_results(self, tickers: list[str] | None) -> list[dict]: ...
    def upsert_earnings_results(self, rows: list[dict]) -> int: ...
